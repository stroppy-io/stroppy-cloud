package cfg

import (
	schemapb "github.com/gopherex/schemapb/go/schemapb"

	"github.com/stroppy-io/stroppy-cloud/pipelines/schemas/ids"
)

// mppGuc is one numeric GUC of the Greenplum family.
type mppGuc struct {
	name, title, group, unit, desc string
	lo, hi                         int64
}

// MppGucs1 is cfg.mpp.gucs@1 — the GUCs a Greenplum-family cluster is told
// with gpconfig after gpinitsystem. One file per role: the coordinator's
// values and the segments' values differ (memory per segment instance,
// connection limits). Every field is unset by default: an unset GUC keeps the
// engine's own value, so the list shows exactly what the deployment changed.
//
// The GUCs exist in all five engines unless a Desc says otherwise; each name
// is checked against the guc-list of Greenplum 6 and 7 and Cloudberry, and the
// values the auto tuning writes are in docs/tuning/mpp.md.
//
// Order is part of the file: max_statement_mem comes before statement_mem,
// because the server refuses a statement_mem that is not below it.
//
// doc: https://techdocs.broadcom.com/us/en/vmware-tanzu/data-solutions/tanzu-greenplum/7/greenplum-database/ref_guide-config_params-guc-list.html
// doc: https://cloudberry.apache.org/docs/config-params-guc-list/
func MppGucs1() *schemapb.Schema {
	var fields []schemapb.FieldDef
	var l pgLines
	l.f("# GUCs for gpconfig — generated by stroppy; unset keys keep the engine's value.")

	numeric := func(g mppGuc) {
		fields = append(fields, schemapb.Int64(schemapb.FieldName(g.name)).Title(g.title).Group(schemapb.GroupName(g.group)).Unit(g.unit).Desc(g.desc).Gte(g.lo).Lte(g.hi).Nullable())
		suffix := ""
		if g.unit == "MB" && g.name != "gp_vmem_protect_limit" {
			suffix = "MB"
		}
		l.f("{{#values.%s}}%s = {{{.}}}%s\n{{/values.%s}}", g.name, g.name, suffix, g.name)
	}
	choice := func(name, title, group, desc string, options ...string) {
		c := schemapb.Choice(schemapb.FieldName(name)).Title(title).Group(schemapb.GroupName(group)).Desc(desc)
		for _, o := range options {
			c = c.Opt(schemapb.StrV(o), o)
		}
		fields = append(fields, c.Nullable())
		l.f("{{#values.%s}}%s = {{{.}}}\n{{/values.%s}}", name, name, name)
	}

	// Memory. doc: admin_guide-wlmgmt_intro, ref_guide guc-list — gp_vmem_protect_limit.
	numeric(mppGuc{
		"gp_vmem_protect_limit", "Segment memory limit", "Memory", "MB",
		"Memory one segment instance (or the coordinator) may use for all its queries; the server cancels the biggest query above it. Engine default 8192, which caps a big host unless raised.", 128, 1048576,
	})
	numeric(mppGuc{
		"max_statement_mem", "Max statement memory", "Memory", "MB",
		"Upper bound of statement_mem for any session. Engine default 2000; statement_mem must stay below it, so it is written first.", 2, 1048576,
	})
	numeric(mppGuc{
		"statement_mem", "Statement memory", "Memory", "MB",
		"Memory one query may use on one segment before operators spill to disk. Engine default 125; must be below max_statement_mem.", 1, 1048576,
	})
	numeric(mppGuc{
		"work_mem", "Work memory", "Memory", "MB",
		"Memory of one sort or hash step before it spills (engine default 32).", 1, 1048576,
	})
	numeric(mppGuc{
		"shared_buffers", "Shared buffers", "Memory", "MB",
		"Shared buffer pool of each segment instance (engine default 125). Analytic scans barely use it.", 16, 1048576,
	})
	numeric(mppGuc{
		"effective_cache_size", "Effective cache size", "Memory", "MB",
		"The PostgreSQL planner's guess of the cache one segment instance can count on; GPORCA does not read it.", 1, 8388608,
	})
	numeric(mppGuc{
		"runaway_detector_activation_percent", "Runaway detector threshold", "Memory", "%",
		"Share of gp_vmem_protect_limit above which the server starts cancelling the biggest queries (engine default 90).", 1, 100,
	})
	choice("gp_resource_manager", "Resource manager", "Memory",
		"How concurrency and memory of queries are managed: queue = resource queues (all engines), group = cgroups (needs a cgroup setup the images do not have), none = no manager (7.x and Cloudberry).",
		"queue", "group", "none")

	// Planner.
	choice("optimizer", "GPORCA", "Planner",
		"on = GPORCA plans queries, off = the PostgreSQL-based planner. The optimizer parameter of the database sets it.", "on", "off")
	choice("gp_autostats_mode", "Automatic statistics", "Planner",
		"When a statement triggers ANALYZE on its own: none, on_change or on_no_stats. 6.x engines default to on_no_stats, 7.x and Cloudberry to none.",
		"none", "on_change", "on_no_stats")
	choice("autovacuum", "Autovacuum", "Planner", "Background vacuum and analyze of the catalogs.", "on", "off")

	// Interconnect.
	choice("gp_interconnect_type", "Interconnect type", "Interconnect",
		"Transport of motion data between segments: udpifc (every engine's default), tcp or proxy.", "udpifc", "tcp", "proxy")
	numeric(mppGuc{
		"gp_max_packet_size", "Interconnect packet size", "Interconnect", "bytes",
		"Largest UDP packet of the interconnect (engine default 8192, which assumes jumbo frames). 1420 fits a 1500-byte MTU without IP fragmentation.", 512, 65536,
	})
	numeric(mppGuc{
		"gp_interconnect_queue_depth", "Receive queue depth", "Interconnect", "packets",
		"Packets a receiver queues per sender (engine default 4).", 1, 4096,
	})
	numeric(mppGuc{
		"gp_interconnect_snd_queue_depth", "Send queue depth", "Interconnect", "packets",
		"Packets a sender keeps in flight per receiver (engine default 2).", 1, 4096,
	})

	// Connections.
	numeric(mppGuc{
		"max_connections", "Connections", "Connections", "",
		"Client connections of the coordinator; on segments every session of the coordinator opens one connection per slice, so segments need at least 3 times the coordinator's value.", 1, 262143,
	})

	// Failure detection. With no mirrors a segment marked down stops the cluster,
	// so a slow probe under load must not be mistaken for a failure.
	numeric(mppGuc{
		"gp_fts_probe_timeout", "FTS probe timeout", "Fault detection", "s",
		"How long the fault prober waits for a segment to answer (engine default 20).", 1, 3600,
	})
	numeric(mppGuc{
		"gp_fts_probe_interval", "FTS probe interval", "Fault detection", "s",
		"Time between probes of all segments (engine default 60).", 10, 3600,
	})
	numeric(mppGuc{
		"gp_segment_connect_timeout", "Segment connect timeout", "Fault detection", "s",
		"How long the coordinator waits for a segment to accept a connection (engine default 180).", 1, 86400,
	})

	// WAL. The 6.x engines (PostgreSQL 9.4 base) have checkpoint_segments
	// instead, which gpconfig refuses to change.
	numeric(mppGuc{
		"max_wal_size", "Max WAL size", "WAL", "MB",
		"WAL size that triggers a checkpoint. PostgreSQL 12 and 14 bases only (7.x, 8.x and Cloudberry).", 32, 1048576,
	})

	fields = append(fields, customField(), customRendered())
	l.f("{{#values.custom_rendered}}\n# --- custom ---\n{{{values.custom_rendered}}}\n{{/values.custom_rendered}}")

	return schemapb.NewSchema(ids.Cfg("mpp.gucs", 1)).
		Descr("GUCs applied with gpconfig to a Greenplum-family cluster, one list per role.").
		Strict().Coerce().
		Fields(fields...).
		Rules(customKeyRule()).
		Template("conf", l.b.String()).
		MustBuild()
}
