package cfg

import (
	schemapb "github.com/gopherex/schemapb/go/schemapb"

	"github.com/stroppy-io/stroppy-cloud/pipelines/schemas/ids"
)

// MppGpinitsystem1 is cfg.mpp.gpinitsystem@1 — the gpinitsystem_config of a
// Greenplum-family cluster without mirrors and without a standby coordinator.
//
// The coordinator's keys are spelled by the PostgreSQL base of the engine:
// MASTER_* on 9.4 (6.x engines), COORDINATOR_* on 12 and 14 (the 9.4 spelling
// is gone from the 7.x documentation but still accepted, the new one is not
// understood by 6.x). The server picks it into coordinator_keyword.
//
// doc: https://techdocs.broadcom.com/us/en/vmware-tanzu/data-solutions/tanzu-greenplum/7/greenplum-database/utility_guide-ref-gpinitsystem.html
// doc: https://github.com/stroppy-io/mpp-builds — "Reproducing the deployment shape"
func MppGpinitsystem1() *schemapb.Schema {
	return schemapb.NewSchema(ids.Cfg("mpp.gpinitsystem", 1)).
		Descr("gpinitsystem_config of a Greenplum-family cluster: primaries only, no standby coordinator.").
		Strict().Coerce().
		Fields(
			// doc: gpinitsystem — ARRAY_NAME
			schemapb.Str("array_name").Title("Array name").Group("Cluster").
				Desc("ARRAY_NAME, the display name of the cluster.").
				Pattern(`^[A-Za-z0-9_ -]+$`).MaxLen(64).Default("stroppy"),
			// doc: gpinitsystem — SEG_PREFIX
			schemapb.Str("seg_prefix").Title("Segment prefix").Group("Cluster").
				Desc("SEG_PREFIX of the segment data directories (gpseg0, gpseg1, …).").
				Pattern(`^[A-Za-z0-9_]+$`).MaxLen(32).Default("gpseg"),
			// doc: gpinitsystem — PORT_BASE; the sample asks for a base below net.ipv4.ip_local_port_range
			schemapb.Int64("port_base").Title("Primary port base").Group("Cluster").
				Desc("PORT_BASE: the first primary segment's port; the next ones count up. Must lie below the kernel's ephemeral port range.").
				Gte(1024).Lte(65000).Default(6000),
			// doc: gpinitsystem — ENCODING
			schemapb.Str("encoding").Title("Encoding").Group("Cluster").
				Desc("ENCODING of the template database and of the cluster's databases.").
				Pattern(`^[A-Za-z0-9_-]+$`).MaxLen(32).Default("UNICODE"),
			// doc: gpinitsystem — DATABASE_NAME, created by gpinitsystem itself
			schemapb.Str("database_name").Title("Database").Group("Cluster").
				Desc("DATABASE_NAME: the database gpinitsystem creates after the cluster is up.").
				Pattern(`^[a-z_][a-z0-9_]*$`).MaxLen(63).Default("stroppy"),

			// Filled by the server from the topology.
			schemapb.Choice("coordinator_keyword").Title("Coordinator keyword").Group("Cluster").
				Desc("Spelling of the coordinator keys: MASTER on a PostgreSQL 9.4 base, COORDINATOR on 12 and 14. Filled by the server from the engine version.").
				Opt(schemapb.StrV("COORDINATOR"), "COORDINATOR_*").
				Opt(schemapb.StrV("MASTER"), "MASTER_*").
				Default(schemapb.StrV("COORDINATOR")),
			schemapb.Str("coordinator_hostname").Title("Coordinator address").Group("Cluster").
				Desc("COORDINATOR_HOSTNAME: the coordinator's private address. Filled by the server from topology.").
				MaxLen(255).Nullable(),
			schemapb.Str("coordinator_directory").Title("Coordinator directory").Group("Cluster").
				Desc("COORDINATOR_DIRECTORY on the coordinator's data volume.").
				Pattern(`^/[A-Za-z0-9._/-]+$`).MaxLen(255).Default("/data/mpp/coordinator"),
			schemapb.Int64("coordinator_port").Title("Coordinator port").Group("Cluster").
				Desc("COORDINATOR_PORT: where clients connect.").
				Gte(1024).Lte(65535).Default(5432),
			schemapb.List("data_directories", schemapb.Str("").Pattern(`^/[A-Za-z0-9._/-]+$`).MaxLen(255)).
				Title("Primary directories").Group("Cluster").
				Desc("DATA_DIRECTORY: one entry per primary segment of a segment host; entries may repeat, every segment gets its own gpseg<N> directory inside. Filled by the server from segments_per_host.").
				MaxItems(64).Nullable(),
			schemapb.Computed("data_directory",
				`("data_directories" in root) && size(root.data_directories) > 0 ? "(" + root.data_directories.join(" ") + ")" : "(/data/mpp/primary)"`).
				Title("DATA_DIRECTORY").Group("Cluster").
				Desc("The `data_directories` list as the bash array gpinitsystem reads.").
				Result(schemapb.ResultString),
		).
		Template("conf", `# gpinitsystem_config — generated by stroppy; primaries only, no mirrors, no standby coordinator.
ARRAY_NAME="{{{values.array_name}}}"
SEG_PREFIX={{{values.seg_prefix}}}
PORT_BASE={{{values.port_base}}}
declare -a DATA_DIRECTORY={{{values.data_directory}}}
{{#values.coordinator_hostname}}{{{values.coordinator_keyword}}}_HOSTNAME={{{.}}}
{{/values.coordinator_hostname}}{{{values.coordinator_keyword}}}_DIRECTORY={{{values.coordinator_directory}}}
{{{values.coordinator_keyword}}}_PORT={{{values.coordinator_port}}}
TRUSTED_SHELL=ssh
ENCODING={{{values.encoding}}}
DATABASE_NAME={{{values.database_name}}}
`).
		MustBuild()
}
