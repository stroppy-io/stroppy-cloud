// pgLines accumulates the "conf" template.
type pgLines struct{ b strings.Builder }

func (l *pgLines) f(format string, a ...any) { fmt.Fprintf(&l.b, format+"\n", a...) }

// num prints `name = <value><unit>` unconditionally (the field always has a
// default, so values.<name> is always set).
func (l *pgLines) num(name, unit string) { l.f("%s = {{{values.%s}}}%s", name, name, unit) }

// bare prints `name = <value>` for enums / on-off choices (never quoted).
func (l *pgLines) bare(name string) { l.f("%s = {{{values.%s}}}", name, name) }

// quoted prints `name = '<value>'`.
func (l *pgLines) quoted(name string) { l.f("%s = '{{{values.%s}}}'", name, name) }

// optQuoted prints `name = '<value>'` only when the value is set and non-empty.
func (l *pgLines) optQuoted(name string) {
	l.f("{{#values.%s}}%s = '{{{.}}}'\n{{/values.%s}}", name, name, name)
}

func (l *pgLines) section(title string) { l.f("\n# --- %s ---", title) }

// postgresqlConf builds cfg.postgresql.conf@<major> for majors 15..18.
//
// Every parameter and default below is the upstream default documented for
// that major (see the `doc:` comments), with three deliberate product
// exceptions, each explained in its Desc: listen_addresses, timezone and
// lc_messages. Version gates, all verified against the per-major docs:
//
//	effective_io_concurrency         1 (15-17) -> 16 (18)
//	io_method, io_workers            18 only
//	autovacuum_vacuum_max_threshold  18 only
//	autovacuum_worker_slots          18 only
//	log_connections                  boolean (15-17) -> aspect list (18)
//	reserved_connections             16+
//	transaction_timeout              17+
//
//nolint:funlen,maintidx // one flat parameter table plus its template
func postgresqlConf(major uint64) *schemapb.SchemaB {
	return schemapb.NewSchema(ids.Cfg("postgresql.conf", major)).
		Descr(fmt.Sprintf(
			"postgresql.conf for PostgreSQL %d — every parameter verified against the %d docs.", major, major)).
		Strict().Coerce().
		Fields(pgConfFields(major, nil)...).
		Rules(pgConfRules()...).
		Template("conf", pgConfTemplate(major, nil))
}

// pgConfExtra injects extra fields and template lines just before the
// `custom` tail; cfg.orioledb.postgresql.conf uses it to bolt the orioledb.*
// block onto the stock PostgreSQL 17 file.
type pgConfExtra func(add func(schemapb.FieldDef), l *pgLines)

func pgConfFields(major uint64, extra pgConfExtra) []schemapb.FieldDef {
	fields, _ := pgConfParts(major, extra)
	return fields
}

func pgConfTemplate(major uint64, extra pgConfExtra) string {
	_, tmpl := pgConfParts(major, extra)
	return tmpl
}

