#!/usr/bin/env python3
"""Write web/src/api/enums.ts: the values of every named string enum of the
contract (components.schemas.<Name> with an `enum`), as typed arrays the SPA
iterates (translations, filters) — openapi-typescript emits the types only.
"""
import json
import sys
import yaml

HEADER = """// Code generated by scripts/openapi_enums.py from openapi/openapi.yaml. DO NOT EDIT.
// Every named string enum of the contract as the list of its values.
import type { components } from './schema'

type Schemas = components['schemas']
"""


def lower_first(name: str) -> str:
    return name[0].lower() + name[1:]


def main() -> int:
    src, out = sys.argv[1], sys.argv[2]
    with open(src) as f:
        spec = yaml.safe_load(f)
    lines = [HEADER]
    for name, schema in sorted(spec.get("components", {}).get("schemas", {}).items()):
        if schema.get("type") != "string" or "enum" not in schema:
            continue
        values = ", ".join(json.dumps(v) for v in schema["enum"])
        lines.append(f"export const {lower_first(name)}Values = [{values}] as const satisfies readonly Schemas['{name}'][]\n")
    with open(out, "w") as f:
        f.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
