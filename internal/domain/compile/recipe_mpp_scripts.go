package compile

import (
	"strings"
	"text/template"
)

// The two scripts that bring a Greenplum-family cluster up. The coordinator
// container runs the first one as root, as the CMD of the image entrypoint
// (which has already started sshd); it prepares what only root can do and
// runs the second one as gpadmin in an ssh session, because the engine's
// utilities need the session: sshd gives them $USER and the pam_limits file
// limits, and `docker exec` or `su` gives neither.
//
// doc: https://github.com/stroppy-io/mpp-builds — "Reproducing the deployment shape", "Notes for the deployer"

// mppInitScript is mpp-init.sh, run as root. It is idempotent across a
// container restart: an existing cluster is only started again.
const mppInitScript = `#!/usr/bin/env bash
# Generated by stroppy-cloud. Runs as root in the coordinator container.
set -euo pipefail
READY={{.Ready}}
rm -f "$READY"
SELF={{.Self}}
HOSTS="{{.Hosts}}"

as_gpadmin() { runuser -u gpadmin -- "$@"; }

# 1. Every sshd answers to gpadmin's key, the coordinator's own included.
for host in $HOSTS; do
  tries=0
  until as_gpadmin ssh -o BatchMode=yes -o ConnectTimeout=5 "$host" true 2>/dev/null; do
    tries=$((tries + 1))
    if [ "$tries" -ge 150 ]; then echo "sshd of $host does not answer" >&2; exit 1; fi
    sleep 2
  done
done

# 2. The engine's utilities address a host by the name it reports, and the
# name of a cloud VM is unknown when the run is compiled: ask every host and
# map the name to its address here. A name must not stay mapped to a loopback
# address (the interconnect would then resolve the host to itself).
table=$(mktemp)
cp /etc/hosts "$table"
for host in $HOSTS; do
  name=$(as_gpadmin ssh -o BatchMode=yes "$host" hostname)
  if [[ ! $name =~ ^[A-Za-z0-9][A-Za-z0-9.-]*$ ]]; then echo "unusable host name '$name' of $host" >&2; exit 1; fi
  grep -v -E "(^|[[:space:]])${name//./\\.}([[:space:]]|\$)" "$table" >"$table.next" || true
  mv "$table.next" "$table"
  echo "$host $name" >>"$table"
done
cat "$table" >/etc/hosts
rm -f "$table"

# 3. The cluster, over ssh as gpadmin.
if as_gpadmin test -f {{.CoordinatorDir}}/gpseg-1/postgresql.conf; then mode=start; else mode=init; fi
as_gpadmin ssh -T -o BatchMode=yes "$SELF" bash {{.ScriptDir}}/mpp-cluster.sh "$mode"

touch "$READY"
exec sleep infinity
`

// mppClusterScript is mpp-cluster.sh, run as gpadmin over ssh with the mode
// init (a new cluster) or start (the cluster of an earlier start of this
// container).
const mppClusterScript = `#!/usr/bin/env bash
# Generated by stroppy-cloud. Runs as gpadmin in an ssh session on the coordinator.
set -euo pipefail
. /usr/local/mpp/env.sh
export COORDINATOR_DATA_DIRECTORY={{.CoordinatorDir}}/gpseg-1 MASTER_DATA_DIRECTORY={{.CoordinatorDir}}/gpseg-1 PGPORT={{.Port}}

if [ "$1" = start ]; then
  gpstart -a
  exit 0
fi

# 1. The data directories and the hostfile of the segment hosts.
mkdir -p {{.CoordinatorDir}}
for host in {{.Segments}}; do ssh "$host" 'mkdir -p {{.PrimaryDir}}'; done
printf '%s\n' {{.Segments}} >"$HOME/hostfile_segments"

# 2. The cluster. Exit code 1 is success with warnings.
#    (gpinitsystem 6 appends to its config file, so it gets a writable copy.)
cp {{.ScriptDir}}/gpinitsystem_config "$HOME/gpinitsystem_config"
rc=0
gpinitsystem -a -c "$HOME/gpinitsystem_config" -h "$HOME/hostfile_segments" || rc=$?
if [ "$rc" -gt 1 ]; then exit "$rc"; fi

# 3. The GUCs, in the order of the files: a key of the segments' list goes to
# the whole cluster with the coordinator's own value (-m) where that differs
# (gpconfig refuses max_connections that is not greater on the segments, so
# both values go in one call); a key only the coordinator's list has goes to
# the coordinator. Then a restart (max_connections and the memory limits
# need one).
gucs() { grep -v -E '^([[:space:]]*#|[[:space:]]*$)' "$1" || true; }
# set_guc sets a key on the whole cluster and reads it back from every
# instance's postgresql.conf: gpconfig exits 0 even when it could not reach a
# segment, and a segment left with statement_mem but not max_statement_mem
# refuses to start.
set_guc() {
  gpconfig -c "$@"
  local check
  check=$(gpconfig -s "$1" --file 2>&1 || true)
  if ! grep -q "Values on all segments are consistent" <<<"$check"; then
    echo "gpconfig: $1 did not reach every instance:" >&2
    echo "$check" >&2
    exit 1
  fi
}
segment_gucs=$(gucs {{.ScriptDir}}/mpp-gucs-segments.conf)
coordinator_gucs=$(gucs {{.ScriptDir}}/mpp-gucs-coordinator.conf)
while IFS= read -r line; do
  if [ -z "$line" ]; then continue; fi
  key=${line%% = *}
  value=${line#* = }
  own=$(grep -E "^${key} = " <<<"$coordinator_gucs" || true)
  if [ -n "$own" ] && [ "${own#* = }" != "$value" ]; then
    set_guc "$key" -v "$value" -m "${own#* = }"
  else
    set_guc "$key" -v "$value"
  fi
done <<<"$segment_gucs"
while IFS= read -r line; do
  if [ -z "$line" ]; then continue; fi
  key=${line%% = *}
  if grep -qE "^${key} = " <<<"$segment_gucs"; then continue; fi
  gpconfig -c "$key" -v "${line#* = }" {{.CoordinatorOnly}}
done <<<"$coordinator_gucs"
gpstop -ar

# 4. The login of the workload, and the addresses it connects from: the
# coordinator's own subnet, the runner and the exporter on the loopback.
psql -X -v ON_ERROR_STOP=1 -d postgres <<'SQL'
CREATE ROLE {{.User}} LOGIN PASSWORD '{{.Password}}';
ALTER DATABASE {{.Database}} OWNER TO {{.User}};
SQL
subnet=$(ip -o -4 addr show | awk -v ip="{{.Self}}" '{ split($4, a, "/"); if (a[1] == ip) { print $4; exit } }')
{
  echo "host all {{.User}} 127.0.0.1/32 md5"
  if [ -n "$subnet" ]; then echo "host all {{.User}} $subnet md5"; fi
  echo "host all {{.User}} {{.Runner}}/32 md5"
} >>"$COORDINATOR_DATA_DIRECTORY/pg_hba.conf"
gpstop -u
`

// mppScriptParts is what the scripts are written for.
type mppScriptParts struct {
	Ready, Self, Hosts, Segments       string
	CoordinatorDir, PrimaryDir         string
	ScriptDir, CoordinatorOnly, Runner string
	Port                               int
	User, Password, Database           string
}

// mppScripts renders the two scripts.
func mppScripts(p mppScriptParts) (initScript, clusterScript string, err error) {
	render := func(name, text string) (string, error) {
		t, err := template.New(name).Option("missingkey=error").Parse(text)
		if err != nil {
			return "", err
		}
		var b strings.Builder
		if err := t.Execute(&b, p); err != nil {
			return "", err
		}
		return b.String(), nil
	}
	if initScript, err = render("mpp-init.sh", mppInitScript); err != nil {
		return "", "", err
	}
	clusterScript, err = render("mpp-cluster.sh", mppClusterScript)
	return initScript, clusterScript, err
}
